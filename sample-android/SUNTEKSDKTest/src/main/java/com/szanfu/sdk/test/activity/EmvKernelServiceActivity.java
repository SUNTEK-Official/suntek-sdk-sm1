    int tipDialog(final String title, final String message) {

        final CountDownLatch latch = new CountDownLatch(1);
        final int[] resultHolder = new int[1];

        runOnUiThread(new Runnable() {
            @Override
            public void run() {
                AlertDialog.Builder builder = new AlertDialog.Builder(mContext);
                builder.setTitle(title);
                builder.setMessage(message);
                //builder.setIcon(R.mipmap.ic_launcher);
                builder.setCancelable(false);
                builder.setPositiveButton("OK", new DialogInterface.OnClickListener() {
                    @Override
                    public void onClick(DialogInterface dialog, int which) {
                        resultHolder[0] = 0;
                        latch.countDown();

                        dialog.dismiss();
                    }
                });
                builder.setNegativeButton("Cancel", new DialogInterface.OnClickListener() {
                    @Override
                    public void onClick(DialogInterface dialog, int which) {
                        resultHolder[0] = -1;
                        latch.countDown();

                        dialog.dismiss();
                    }
                });
                /*
                builder.setNeutralButton("Middle", new DialogInterface.OnClickListener() {
                    @Override
                    public void onClick(DialogInterface dialog, int which) {
                        dialog.dismiss();
                    }
                });
                */
                mConfirmPanDialog = builder.create();
                mConfirmPanDialog.show();
            }
        });

        try {
            latch.await();
        } catch (InterruptedException e) {
            e.printStackTrace();
        }

        return resultHolder[0];
    }

