    public void getCiphertextDataX(String itemName) {
        try {
            Map<Integer, String> param3Map = new HashMap<>();
            param3Map.put(1, "PAN");
            param3Map.put(2, "Track2");
            param3Map.put(3, "Track3");

            Map<Integer, String> paddingModeMap = new HashMap<>();
            paddingModeMap.put(1, "Padding 0x00");
            paddingModeMap.put(2, "Padding 0x80");
            paddingModeMap.put(3, "Padding 0xFF");
            paddingModeMap.put(4, "Padding PKCS5");

            int[] paramModes = {1, 2};
            int[] paddingModes = {1, 2, 3, 4};

            Map<Integer, Integer> encryptionPairs = new HashMap<>();
            encryptionPairs.put(0x11, 0x10);
            encryptionPairs.put(0x21, 0x20);
            encryptionPairs.put(0x41, 0x40);
            encryptionPairs.put(0x81, 0x80);


            Map<Integer, String> errorMessages = new HashMap<>();
            errorMessages.put(-9000, "DUKPT key index must be between 11-30");
            errorMessages.put(-9001, "KSN length is abnormal");
            errorMessages.put(-9002, "Invalid keyType (must be 1, 4, or 5)");
            errorMessages.put(-9003, "Encryption/Decryption mode parameter is abnormal");
            errorMessages.put(-9004, "CBC mode IV must be non-null and 16 bytes");
            errorMessages.put(-9005, "DUKPT key does not exist");
            errorMessages.put(-9006, "Invalid DATA TYPE (must be PAN, Track2, Track3)");
            errorMessages.put(-9007, "PAN/Track data is empty");
            errorMessages.put(-9008, "Invalid padding mode");

            for (int itemParam : paramModes) {
                for (int paddingMode : paddingModes) {
                    for (Map.Entry<Integer, Integer> entry : encryptionPairs.entrySet()) {
                        int encMode = entry.getKey();
                        int decMode = entry.getValue();
                        String[] outData = new String[1];

                        String paramStr = param3Map.getOrDefault(itemParam, "Unknown");
                        String paddingModeStr = paddingModeMap.getOrDefault(paddingMode, "Unknown");


                        int result = mSystemBinderService.dukptGetCiphertextData(
                                KEY_INDEX_DUKPT_INDEX_PIN_18, 4, itemParam, outData, "0000000000000000", encMode, paddingMode, 8
                        );

                        if (result <= 0 || outData[0] == null || outData[0].isEmpty()) {
                            String errorMsg = errorMessages.getOrDefault(result, "Unknown encryption error");
                            String logMessage = String.format(
                                    "[Encryption Error] Param: %s, Padding: %s, EncMode: 0x%02X, ErrorCode: %d (%s)",
                                    paramStr, paddingModeStr, encMode, result, errorMsg
                            );
                            LogUtils.e( logMessage);
                            appendText(logMessage + "\n");
                            appendText("Encryption failed, stopping test.\n");
                            return;
                        }

                        String logMessage = String.format(
                                "[Encryption] Param: %s, Padding: %s, EncMode: 0x%02X -> DataLen: %d, Data: %s",
                                paramStr, paddingModeStr, encMode, result, outData[0]
                        );
                        LogUtils.i( logMessage);
                        appendText(logMessage + "\n");


                        String[] decOutData = new String[1];
                        int dukptEncDec = mSystemBinderService.dukptEncDec(
                                KEY_INDEX_DUKPT_INDEX_PIN_18, 4, outData[0], decOutData, "0000000000000000", decMode, 0
                        );

                        if (dukptEncDec != 0) {
                            String errorMsg = errorMessages.getOrDefault(dukptEncDec, "Unknown decryption error");
                            String decMessage = String.format(
                                    "[Decryption Error] Param: %s, DecMode: 0x%02X, ErrorCode: %d (%s)",
                                    paramStr, decMode, dukptEncDec, errorMsg
                            );
                            LogUtils.e( decMessage);
                            appendText(decMessage + "\n");
                            appendText("Decryption failed, stopping test.\n");
                            return;
                        }

                        String decMessage = String.format(
                                "[Decryption] Param: %s, DecMode: 0x%02X -> Success: %s",
                                paramStr, decMode, decOutData[0]
                        );
                        LogUtils.e( decMessage);
                        appendText(decMessage + "\n");
                    }
                }
            }
        } catch (RemoteException e) {
            e.printStackTrace();
            appendText("RemoteException occurred, stopping test.\n");
        }
    }
