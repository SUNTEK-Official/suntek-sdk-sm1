    private class NoLeakHandler extends Handler {
        private WeakReference<EmvKernelServiceActivity> weakReference;

        public NoLeakHandler(EmvKernelServiceActivity activity) {
            weakReference = new WeakReference<EmvKernelServiceActivity>(activity);
        }

        @Override
        public void handleMessage(final Message msg) {
            super.handleMessage(msg);
            final EmvKernelServiceActivity activity = weakReference.get();
            if (activity == null) {
                return;
            }

            switch (msg.what) {

                case TransHelper.MSG_ON_CANCEL: {
                    UI_Toast("Transaction Cancel");
                }
                break;

                case TransHelper.MSG_ENTER_ONLINE_PIN: {
                    new Thread(new Runnable() {
                        @Override
                        public void run() {
                            showPinPad(true,
                                    TransHelper.getInstance().card_pan,
                                    PIN_TYPE_ONLINE_PIN);
                        }
                    }).start();
                }
                break;

                case TransHelper.MSG_ONLINE_COMM_MSR: {
                    DoOnline_MSR();
                }
                break;

                case TransHelper.MSG_ONLINE_COMM_PICC: {
                    DoOnline_PICC();
                }
                break;
            }
        }
    }

