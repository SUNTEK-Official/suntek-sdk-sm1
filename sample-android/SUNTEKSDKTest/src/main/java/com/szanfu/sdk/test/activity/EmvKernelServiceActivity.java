    /**
     * 是否需要发起联机交易
     * Check whether a connection transaction needs to be initiated
     *
     * @param type 0:GAC1 1: GAC2
     */
    private void apiEmvGetKernelProcessResult(int type) {

        try {
            LogUtils.i( "apiEmvGetKernelProcessResult: " + (type == 0 ? "===GAC1===" : "===GAC2==="));
            appendInfoText("apiEmvGetKernelProcessResult--> " + (type == 0 ? "===GAC1===" : "===GAC2==="));


            EmvGetKernelProgressResult emvGetKernelProgressResult = mEmvBinderService.emvGetKernelProgressResult();

            if (emvGetKernelProgressResult == null) {
                UI_Toast("The kernel returns an abnormal result...");
                appendErrorText("apiEmvGetKernelProcessResult: The kernel returns an abnormal result");
                return;
            }

            int ret = emvGetKernelProgressResult.getRet();
            appendTextResult(ret, "EmvCompletion ret :" + ret);

            /*
             * 调用emvGetKernelProcessResult(ST_KERNEL_RESULT);接口判断是否需要发动联机操作
             * // (kernel processing result)
             * typedef struct
             * {
             *     unsigned char ucKernel; // (kernel type)
             *     unsigned char ucStatus; // OPS Status
             *     unsigned char ucStart; // add at 2020 09 02 by
             *     unsigned char ucCvm; // OPS CVM
             *     unsigned char ucCmd; // (last APDU command type
             *     unsigned char ucErrL1;          // L1
             *     unsigned char ucErrL2;          // L2
             *     unsigned char ucErrL3;          // L3
             *     unsigned char aucSw1Sw2[2];     // SW1SW2
             *     unsigned char ucIdentify; // UIRD Message Identifier
             * } ST_KERNEL_RESULT;
             */
            byte[] kernelData = emvGetKernelProgressResult.getTagData();
            try {
                if (kernelData != null) {
                    appendInfoText("kernelData: " + HexSupport.toHexFromBytes(kernelData));
                    appendText("    ucKernel: " + HexSupport.toHexFromByte(kernelData[0]));
                    appendText("    ucStatus: " + HexSupport.toHexFromByte(kernelData[1]));
                    appendText("    ucStart: " + HexSupport.toHexFromByte(kernelData[2]));
                    appendText("    ucCvm: " + HexSupport.toHexFromByte(kernelData[3]));
                    appendText("    ucCmd: " + HexSupport.toHexFromByte(kernelData[4]));
                    appendText("    ucErrL1: " + HexSupport.toHexFromByte(kernelData[5]));
                    appendText("    ucErrL2: " + HexSupport.toHexFromByte(kernelData[6]));
                    appendText("    ucErrL3: " + HexSupport.toHexFromByte(kernelData[7]));
                    appendText("    aucSw1Sw2: " + HexSupport.toHexFromByte(kernelData[8]) + HexSupport.toHexFromByte(kernelData[9]));
                    appendText("    ucIdentify: " + HexSupport.toHexFromByte(kernelData[10]));
                }
            } catch (Throwable e) {
                e.printStackTrace();
            }

            if (ret != 0 || kernelData == null) {
                UI_Toast("emvGetKernelProgressResult Error");
                appendErrorText("emvGetKernelProgressResult Error");
                return;
            }

            /**
             *
             * 根据返回数据内容第二字节：ucStatus的值做后续操作，定义如下 (同OPS中的Status)
             * Perform subsequent operations based on the value of the second byte of the returned data: ucStatus, which is defined as follows
             * #define OPS_STATUS_APPROVED                 0x10 // // Approve
             * #define OPS_STATUS_DECLINED                 0x20 // // Deny
             * #define OPS_STATUS_ONLINE_REQUEST           0x30 // // Online request
             * #define OPS_STATUS_END_APPLICATION          0x40 // // End application (Terminated)
             * #define OPS_STATUS_SELECT_NEXT              0x50 // ( ) // Select next
             * #define OPS_STATUS_TRY_ANOTHER_INTERFACE    0x60 // ( ), // Try another interface (for contactless only)
             * #define OPS_STATUS_TRY_AGAIN                0x70 // L1 timeout CDCVM // Retry
             * #define OPS_STATUS_REVERSAL                 0x80 // (RUPAY ), // Reverse (for RUPAY only)
             * #define OPS_STATUS_NA                       0xF0 // N/A // N/A
             */
            String ucStatus = HexSupport.toHexFromByte(kernelData[1]);
            appendErrorText("Kernel processing results:" + ucStatus);

            if ("10".equals(ucStatus)) {
                if (type == 0) {
                    UI_Toast("Offline Approved");
                    appendInfoText("Offline Approved");
                } else {
                    UI_Toast("Online Approved");
                    appendInfoText("Online Approved");

                    //get Issuer Script Processing Result
                    byte tag_DF31_value[] = getTagValue(0xDF31, "Issue Script Result");
                    if (tag_DF31_value != null) {
                        appendInfoText("Issue Script Result: " + HexSupport.toHexFromBytes(tag_DF31_value));
                    }

                    handler.postDelayed(new Runnable() {
                        @Override
                        public void run() {
                            UI_hide_processing();
                        }
                    }, 1000);

                }

                // TODO: zzzzzz print voucher

            } else if ("20".equals(ucStatus)) {
                if (type == 0) {
                    UI_Toast("Offline Denied");
                    appendInfoText("Offline Denied");
                } else {
                    UI_Toast("Online Denied");
                    appendInfoText("Online Denied");
                }

            } else if ("30".equals(ucStatus)) {
                if (type == 0) {
                    UI_Toast("need online");
                    appendInfoText("need online");
                } else {
                    appendErrorText("why return the ARQC for GAC2 ???");
                    return;
                }

                /**
                 * 如果第二字节提示联机请求，需要再判断第四字节ucCvm,看是否需要执行打印小票签名行或调用联机PIN
                 * (其中如果是执行联机PIN，需要判断是非接交易还是接触交易，接触交易时不做弹密码框处理，非接时需要弹框输密或根据业务需求自主决定是否免密)
                 * 注：接触的，必须内核内回调输入PIN的过程，因为有BY PASS PIN的时候，非接触，内核只是置位，应用层根据内核的置位状态，
                 * 调用输入PIN的过程。到产品中，应用层还可能免密的处理，所以应用层自住决定是否输入PIN。
                 *
                 * If the second byte indicates an online request, you need to check the fourth byte ucCvm to see
                 * if you need to print the receipt signature line or call the online PIN.
                 *
                 * #define OPS_CVM_NO_CVM                  0x00 // CVM No CVM required
                 * #define OPS_CVM_SIGNATURE               0x10 // Signature
                 * #define OPS_CVM_ONLINE_PIN              0x20 // PIN Online PIN
                 * #define OPS_CVM_CONFIRM_CODE_VERIFIED   0x30 // Verification confirmation code
                 * #define OPS_CVM_NA                      0xF0 // CVM：N/A   CVM: N/A
                 */
                String ucCvm = HexSupport.toHexFromByte(kernelData[3]);
                appendInfoText("ucCvm: " + ucCvm);

                TransHelper.getInstance().need_onlinepin = false;
                // TODO: zzzzzz what's the value for other CVM bit, e.g. offline plain/cihper pin" ???
                switch (ucCvm) {
                    case "00":
                        appendText("   ucCvm Result: No CVM required");
                        break;
                    case "10":
                        appendText("   ucCvm Result: Signature");
                        TransHelper.getInstance().need_signature = true;
                        break;
                    case "20":
                        appendText("   ucCvm Result: Online PIN");
                        //UI_Toast("RF Online PIN...");
                        TransHelper.getInstance().need_onlinepin = true;
                        break;
                    case "30":
                        appendText("   ucCvm Result: Verification confirmation code");
                        break;
                    case "F0":
                        appendErrorText("   ucCvm Result: N/A");
                        break;
                    default:
                        appendErrorText("   ucCvm Result: unknown");
                        break;
                }


                switch (TransHelper.getInstance().card_type) {
                    case CardSearchType.IC_CARD: {
                        if (TransHelper.getInstance().need_onlinepin == false) {
                            //EMV kernel not request online PIN
                            if (g_cfg_must_enter_online_pin) {
                                appendInfoText("must enter online PIN for ICC");

                                byte[] currentCardNumber = getTagValue(0x5A, "PAN");
                                appendText("   CardNumber=" + HexSupport.toHexFromBytes(currentCardNumber));

                                UI_hide_processing();
                                showPinPad(true,
                                        HexSupport.toHexFromBytes(currentCardNumber),
                                        PIN_TYPE_ONLINE_PIN);
                            }
                        }

                        //UI_show_processing("processing...");
                        DoOnline_ICC();
                    }
                    return;

                    case CardSearchType.RF_CARD: {
                        if (TransHelper.getInstance().need_onlinepin) {
                            appendInfoText("need enter online PIN for PICC");

                            byte[] currentCardNumber = getTagValue(0x5A, "PAN");
                            appendText("   CardNumber=" + HexSupport.toHexFromBytes(currentCardNumber));

                            String track2data = HexSupport.toHexFromBytes(getTagValue(0x57, "Track2 Equivalent Date"));
                            LogUtils.i("Track2data: " + track2data + "\n");

                            UI_hide_processing();
                            showPinPad(true,
                                    HexSupport.toHexFromBytes(currentCardNumber),
                                    PIN_TYPE_ONLINE_PIN);
                        }

                        UI_show_processing("processing...");
                        DoOnline_PICC();
                    }
                    return;
                }

            } else if ("40".equals(ucStatus)) {
                if (type == 0) {
                    UI_Toast("GAC1: Terminate");
                    appendErrorText("GAC1: Terminate");
                } else {
                    UI_Toast("GAC2: Terminate");
                    appendErrorText("GAC2: Terminate");
                }
                UI_hide_processing();

            } else if ("50".equals(ucStatus)) {
 // ( )
                // TODO: zzzzz how to handle it?
                UI_Toast(getString(R.string.gac1_select_next));
                appendErrorText(getString(R.string.gac1_select_next));

            } else if ("60".equals(ucStatus)) {
                if (TransHelper.getInstance().card_type == CardSearchType.RF_CARD) {
                    UI_Toast(getString(R.string.gac1_try_another_interface));
                    appendErrorText(getString(R.string.gac1_try_another_interface));
                } else {
                    appendErrorText("why ICC return 'Try other interface' ???");
                }

            } else if ("70".equals(ucStatus)) {
 // L1 timeout CDCVM
                if (type == 0) {
                    UI_Toast("Terminate (L1 timeout)");
                    appendInfoText("Terminate (L1 timeout)");
                } else {
                    UI_Toast(getString(R.string.gac1_retry));
                    appendErrorText(getString(R.string.gac1_retry));
                }

            } else if ("80".equals(ucStatus)) {
                if (type == 0) {
                    appendErrorText("Why return 'Reversal' for GAC1 ??? it's Rupay only");
                } else {
                    // TODO: zzzzz how to handle it? what's the reversal code
                    UI_Toast(getString(R.string.gac1_reverse));
                    appendErrorText(getString(R.string.gac1_reverse));
                }

            } else if ("F0".equals(ucStatus)) {
 // N/A
                UI_Toast(getString(R.string.gac1_na));
                appendErrorText(getString(R.string.gac1_na));
            } else {
                appendErrorText("unknown ucStatus: " + ucStatus);
            }

        } catch (RemoteException e) {
            e.printStackTrace();
        }
    }

